CREATE DATABASE IF NOT EXISTS bkash
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE bkash;

CREATE TABLE IF NOT EXISTS bkash_tokens (
    id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
    id_token TEXT NULL,
    refresh_token TEXT NULL,
    expires_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
    grant_window_started_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
    grant_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
      ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

INSERT IGNORE INTO bkash_tokens (id) VALUES (1);

CREATE TABLE IF NOT EXISTS bkash_payments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    invoice VARCHAR(80) NOT NULL UNIQUE,
    payment_id VARCHAR(100) NULL UNIQUE,
    amount DECIMAL(12,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'CREATED',
    trx_id VARCHAR(100) NULL,
    payer_reference VARCHAR(100) NULL,
    create_response LONGTEXT NULL,
    execute_response LONGTEXT NULL,
    query_response LONGTEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
      ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_payment_status (status)
) ENGINE=InnoDB;
